"""
compare_sim_vs_measured.py - line up Pluto bench data with the LTspice model of
the delay-line discriminator and see how well the frequency can be recovered.

    %USERPROFILE%\\radioconda\\python.exe compare_sim_vs_measured.py measurements\\meas_XXXX.csv --dl-in 4.5 --vf 0.70
    %USERPROFILE%\\radioconda\\python.exe compare_sim_vs_measured.py --make-example     # SYNTHETIC test data

CSV columns: freq_hz, v_out_V   (lines starting with # are ignored; blank v_out_V skipped)

What it does
  1. fits  V = a*cos(2*pi*f*dt) + b   (a may be negative = mixer polarity)
     by brute-force dt search + least squares  -> measured delay dt, effective VF
  2. overlays the LTspice curve (../02_delay_line_discriminator, scaled + offset to the data)
  3. inverts the fitted curve and the simulated curve to recover f from V and
     plots the recovery error - i.e. "how well can we tell the transmitted frequency"
"""
from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

import numpy as np
import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

HERE = Path(__file__).resolve().parent
SIM_JSON = HERE.parent / "02_delay_line_discriminator" / "plots" / "results_summary.json"
C0 = 299792458.0


def load_meas(path: Path):
    f, v = [], []
    with open(path) as fh:
        rows = [r for r in fh if r.strip() and not r.lstrip().startswith("#")]
    for r in csv.DictReader(rows):
        s = (r.get("v_out_V") or "").strip()
        if s in ("", "nan"):
            continue
        f.append(float(r["freq_hz"]))
        v.append(float(s))
    return np.array(f), np.array(v)


def fit_cos(f, v, dt_min=0.02e-9, dt_max=3e-9, n=6000):
    best = None
    for dt in np.linspace(dt_min, dt_max, n):
        M = np.c_[np.cos(2 * np.pi * f * dt), np.ones_like(f)]
        c, *_ = np.linalg.lstsq(M, v, rcond=None)
        r = float(np.sum((M @ c - v) ** 2))
        if best is None or r < best[0]:
            best = (r, dt, c)
    r, dt, c = best
    # local refine
    for span in (dt_max / n * 4, dt_max / n / 2):
        grid = np.linspace(dt - span, dt + span, 401)
        for d in grid:
            M = np.c_[np.cos(2 * np.pi * f * d), np.ones_like(f)]
            cc, *_ = np.linalg.lstsq(M, v, rcond=None)
            rr = float(np.sum((M @ cc - v) ** 2))
            if rr < r:
                r, dt, c = rr, d, cc
    rms = np.sqrt(r / len(f))
    return float(dt), float(c[0]), float(c[1]), float(rms)


def invert(v_meas, f_grid, v_grid):
    """nearest-point inverse on the monotonic segment spanning the sweep."""
    return np.array([f_grid[np.argmin(np.abs(v_grid - x))] for x in v_meas])


def sim_curve():
    if not SIM_JSON.exists():
        return None
    s = json.loads(SIM_JSON.read_text())
    var = s["variants"].get("user_dbm") or s["variants"]["user_ideal"]
    items = sorted((float(k.replace("GHz", "")) * 1e9, val) for k, val in var["vout_sim_V"].items())
    return np.array([i[0] for i in items]), np.array([i[1] for i in items]), s, var


def make_example(path: Path, dl_in=4.5, vf_true=0.68):
    rng = np.random.default_rng(1)
    f = np.arange(1.0e9, 1.2e9 + 1, 5e6)
    dt = dl_in * 0.0254 / (vf_true * C0)
    v = -0.12 * np.cos(2 * np.pi * f * dt) + 0.003 + rng.normal(0, 0.0015, len(f))
    with open(path, "w", newline="") as fh:
        fh.write("# SYNTHETIC example data generated by compare_sim_vs_measured.py --make-example - NOT a measurement\n")
        fh.write(f"# true dl_in={dl_in} vf={vf_true} amplitude=-0.12 V offset=3 mV noise=1.5 mV rms\n")
        w = csv.writer(fh)
        w.writerow(["freq_hz", "v_out_V"])
        for a, b in zip(f, v):
            w.writerow([f"{a:.0f}", f"{b:.5f}"])
    print("wrote", path)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("csv", nargs="?")
    ap.add_argument("--dl-in", type=float, default=4.5, help="physical extra length of delayed arm (inches)")
    ap.add_argument("--vf", type=float, default=0.70, help="datasheet velocity factor (for the prediction)")
    ap.add_argument("--band", type=float, nargs=2, default=[1.0e9, 1.2e9], help="band for recovery error")
    ap.add_argument("--make-example", action="store_true")
    ap.add_argument("--free-dt", action="store_true", help="search dt over 0.02-3 ns even for a narrow sweep")
    a = ap.parse_args()

    if a.make_example:
        p = HERE / "measurements" / "example_SYNTHETIC_measurement.csv"
        p.parent.mkdir(exist_ok=True)
        make_example(p, a.dl_in)
        a.csv = str(p)
    if not a.csv:
        ap.error("give a measurement CSV (or --make-example)")
    path = Path(a.csv)
    f, v = load_meas(path)
    if len(f) < 5:
        raise SystemExit("need at least 5 measured points")

    dt_pred = a.dl_in * 0.0254 / (a.vf * C0)
    span = f.max() - f.min()
    if a.free_dt or span * dt_pred > 0.8:
        # >~0.8 fringe covered: dt is well identified, search everything
        dt, amp, ofs, rms = fit_cos(f, v)
    else:
        # narrow sweep (e.g. 1.0-1.2 GHz): many dt fit equally well -> stay near the cable estimate
        dt, amp, ofs, rms = fit_cos(f, v, 0.5 * dt_pred, 1.5 * dt_pred, 3000)
    vf_eff = a.dl_in * 0.0254 / (dt * C0)
    ff = np.linspace(f.min(), f.max(), 2001)
    v_fit = amp * np.cos(2 * np.pi * ff * dt) + ofs

    # prediction with the datasheet VF, only amplitude/offset fitted
    M = np.c_[np.cos(2 * np.pi * f * dt_pred), np.ones_like(f)]
    (amp_p, ofs_p), *_ = np.linalg.lstsq(M, v, rcond=None)
    v_pred = amp_p * np.cos(2 * np.pi * ff * dt_pred) + ofs_p

    sim = sim_curve()
    fig, axs = plt.subplots(3, 1, figsize=(11, 13))
    axs[0].plot(f / 1e9, v * 1e3, "o", label="measured")
    axs[0].plot(ff / 1e9, v_fit * 1e3, "-", label=f"fit: a cos(2 pi f dt)+b, dt = {dt*1e12:.1f} ps (VF_eff = {vf_eff:.3f})")
    axs[0].plot(ff / 1e9, v_pred * 1e3, "--", label=f'prediction {a.dl_in}" @ VF {a.vf} (dt = {dt_pred*1e12:.1f} ps)')
    result = {"csv": str(path), "n_points": int(len(f)), "dl_in": a.dl_in, "vf_datasheet": a.vf,
              "dt_predicted_ps": dt_pred * 1e12, "dt_fit_ps": dt * 1e12, "vf_effective": vf_eff,
              "fit_amplitude_V": amp, "fit_offset_V": ofs, "fit_rms_V": rms}
    if sim is not None:
        fs, vs, s, var = sim
        k = (fs >= f.min() - 1) & (fs <= f.max() + 1)
        if k.sum() >= 3:
            vs_i = np.interp(f, fs, vs)
            M = np.c_[vs_i, np.ones_like(f)]
            (al, be), *_ = np.linalg.lstsq(M, v, rcond=None)
            axs[0].plot(fs[k] / 1e9, (al * vs[k] + be) * 1e3, "s", ms=4, mfc="none",
                        label=f'LTspice ({var["extra_length_in"]}" @ VF {s["velocity_factor"]}), scaled x{al:.2f}')
            result["ltspice_scale"] = float(al)
            result["ltspice_rms_after_scaling_V"] = float(np.sqrt(np.mean((al * vs_i + be - v) ** 2)))
    axs[0].set_xlabel("frequency (GHz)")
    axs[0].set_ylabel("mixer DC out (mV)")
    axs[0].grid(alpha=.3)
    axs[0].legend(fontsize=8)
    axs[0].set_title(path.name)

    axs[1].plot(f / 1e9, (v - (amp * np.cos(2 * np.pi * f * dt) + ofs)) * 1e3, "o-", label="measured - fit")
    axs[1].plot(f / 1e9, (v - (amp_p * np.cos(2 * np.pi * f * dt_pred) + ofs_p)) * 1e3, "s-", label="measured - prediction")
    axs[1].set_xlabel("frequency (GHz)")
    axs[1].set_ylabel("mV")
    axs[1].grid(alpha=.3)
    axs[1].legend(fontsize=8)
    axs[1].set_title("residuals")

    kb = (f >= a.band[0]) & (f <= a.band[1])
    if kb.sum() >= 3:
        fg = np.linspace(a.band[0], a.band[1], 4001)
        f_rec_fit = invert(v[kb], fg, amp * np.cos(2 * np.pi * fg * dt) + ofs)
        f_rec_pred = invert(v[kb], fg, amp_p * np.cos(2 * np.pi * fg * dt_pred) + ofs_p)
        coef = np.polyfit(v[kb], f[kb], 1)
        f_rec_lin = np.polyval(coef, v[kb])
        for rec, lab in ((f_rec_fit, "inverse of fitted curve (calibrated)"),
                         (f_rec_pred, "inverse of datasheet prediction (uncalibrated)"),
                         (f_rec_lin, "straight-line map (analog S&H -> VCO)")):
            axs[2].plot(f[kb] / 1e9, (rec - f[kb]) / 1e6, "o-", ms=3, label=f"{lab}: rms {np.sqrt(np.mean((rec-f[kb])**2))/1e6:.2f} MHz")
            result[f"recovery_rms_MHz__{lab.split(' (')[0].replace(' ', '_')}"] = float(np.sqrt(np.mean((rec - f[kb]) ** 2)) / 1e6)
        slope = abs(amp * 2 * np.pi * dt * np.sin(2 * np.pi * np.mean(a.band) * dt))
        result["noise_limited_resolution_MHz"] = float(rms / slope / 1e6) if slope > 0 else None
    axs[2].set_xlabel("true frequency (GHz)")
    axs[2].set_ylabel("recovered - true (MHz)")
    axs[2].grid(alpha=.3)
    axs[2].legend(fontsize=8)
    axs[2].set_title("How well can the transmitted frequency be recovered from V?")
    fig.tight_layout()
    out_png = path.with_name(path.stem + "_comparison.png")
    fig.savefig(out_png, dpi=130)
    path.with_name(path.stem + "_comparison.json").write_text(json.dumps(result, indent=2))
    print(json.dumps(result, indent=2))
    print("plot ->", out_png)


if __name__ == "__main__":
    main()
